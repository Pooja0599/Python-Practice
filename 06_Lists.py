# ==========================================
# 1. Creating a List
# ==========================================

fruits = ["Apple", "Banana", "Mango", "Orange"]
print("Original List :", fruits)

print("=============================================")

# ==========================================
# 2. Accessing Elements
# ==========================================

print("First Fruit :", fruits[0])
print("Last Fruit :", fruits[-1])

print("=============================================")

# ==========================================
# 3. List Slicing
# ==========================================

print("First Two Fruits :", fruits[:2])
print("Last Two Fruits :", fruits[-2:])

print("=============================================")

# ==========================================
# 4. Update List Element
# ==========================================

fruits[1] = "Grapes"
print("Updated List :", fruits)

print("=============================================")

# ==========================================
# 5. Append Element
# ==========================================

fruits.append("Pineapple")
print("After Append :", fruits)

print("=============================================")

# ==========================================
# 6. Insert Element
# ==========================================

fruits.insert(2, "Kiwi")
print("After Insert :", fruits)

print("=============================================")

# ==========================================
# 7. Extend List
# ==========================================

fruits.extend(["Papaya", "Guava"])
print("After Extend :", fruits)

print("=============================================")

# ==========================================
# 8. Remove Element
# ==========================================

fruits.remove("Orange")
print("After Remove :", fruits)

print("=============================================")

# ==========================================
# 9. Pop Element
# ==========================================

fruits.pop()
print("After Pop :", fruits)

print("=============================================")

# ==========================================
# 10. Sort List
# ==========================================

numbers = [50, 20, 80, 10, 40]
numbers.sort()
print("Sorted List :", numbers)

print("=============================================")

# ==========================================
# 11. Reverse List
# ==========================================

numbers.reverse()
print("Reverse List :", numbers)

print("=============================================")

# ==========================================
# 12. Count Element
# ==========================================

marks = [80, 90, 80, 70, 80]
print("Count of 80 :", marks.count(80))

print("=============================================")

# ==========================================
# 13. Index of Element
# ==========================================

print("Index of 90 :", marks.index(90))

print("=============================================")

# ==========================================
# 14. Length of List
# ==========================================

print("Length of Fruits List :", len(fruits))

print("=============================================")

# ==========================================
# 15. Membership Operator
# ==========================================

print("Apple" in fruits)
print("Cherry" in fruits)

print("=============================================")

print("Lists Completed Successfully.")
print("===============================")


# 6. Arithmetic Operators :- 
a = 20
b = 10

print(a + b)
print(a - b)
print(a * b)
print(a / b)
print(a % b)
print(a // b)
print(a ** b)
print("===============================")


# 7. Comparison Operators :- 
print(a == b)
print(a != b)
print(a > b)
print(a < b)
print(a >= b)
print(a <= b)
print("===============================")


# 8. Logical Operators :- 
x = True
y = False

print(x and y)
print(x or y)
print(not x)
print("===============================")


# 9. Assignment Operators :- 
c = 10
c += 5
print(c)
print("===============================")


# 10. Identity Operators :- 
list1 = [1, 2, 3]
list2 = list1
list3 = [1, 2, 3]

print(list1 is list2)
print(list1 is list3)
print("===============================")


# 11. Membership Operators :- 
fruits = ["Apple", "Banana", "Mango"]

print("Apple" in fruits)
print("Orange" not in fruits)
print("===============================")

